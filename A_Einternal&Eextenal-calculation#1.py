# Process each s2 value
for t in range(-100, 0):

    fb = []  # dynamic: grows to fit all valid (k1,k2,k3,k4) combos for this t

    # Find possible branches of asin()
    for k_1 in range(-3, 4):
        for k_2 in range(-3, 4):
            for k_3 in range(-3, 4):
                for k_4 in range(-3, 4):

                    if (
                        k_1 < k_2
                        and k_2 < k_3
                        and k_3 < k_4
                        and k_1 * k_2 * k_3 * k_4 != 0
                    ):
                        b = [0] * 5
                        b[1] = (asin(s2[t]) - 2 * k_1 * pi) / log(2)
                        b[2] = (asin(s2[t]) - 2 * k_2 * pi) / log(2)
                        b[3] = (asin(s2[t]) - 2 * k_3 * pi) / log(2)
                        b[4] = (asin(s2[t]) - 2 * k_4 * pi) / log(2)

                        # Calculate differences between b values
                        for l1 in range(1, 5):
                            for l2 in range(1, 5):
                                if l1 < l2:
                                    fb.append(b[l1] - b[l2])

    tmax = len(fb)  # number of valid fb entries for this t (fb[0]..fb[tmax-1])

    # Sweep every consecutive pair (fb[t2], fb[t2+1]) -- one row per pair
    for t2 in range(0, tmax - 1):
        fb0 = fb[t2]
        fb_next = fb[t2 + 1]
        denominator = fb_next + fb0

        if denominator != 0:
            Einternal = (Ef * fb_next - Ef * fb0) / denominator
            Eexternal = (2 * Ef * fb0) / denominator

            if Einternal < 0:
                id1 += 1
            if Eexternal < 0:
                id2 += 1
            if Einternal > Eexternal:
                id3 += 1
            total += 1

            print(
                "Einternal =", Einternal,
                " Eexternal =", Eexternal
            )

